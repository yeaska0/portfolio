/* =============================================
   INTERSECTION OBSERVER
============================================= */
const obs = new IntersectionObserver(entries => {
    entries.forEach(entry => {
        if (!entry.isIntersecting) return;
        const el = entry.target;
        el.classList.add('in');

        // Skill bars
        el.querySelectorAll('.fill').forEach(f => {
            setTimeout(() => {
                f.style.width = f.dataset.w + '%';
                setTimeout(() => f.classList.add('done'), 1400);
            }, 180);
        });

        // Counters
        el.querySelectorAll('[data-tg]').forEach(n => {
            const tg = +n.dataset.tg;
            let c = 0;
            const t = setInterval(() => {
                c += tg / 50;
                if (c >= tg) { n.textContent = tg; clearInterval(t); }
                else n.textContent = Math.floor(c);
            }, 28);
        });

        obs.unobserve(el);
    });
}, { threshold: .12 });

document.querySelectorAll('.rv, .rvl, .rvr').forEach(el => obs.observe(el));

